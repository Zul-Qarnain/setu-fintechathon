/** `npm run evidence`: runs the golden tasks, the notice corpus and the attack suite and writes evidence/*.md|json from REAL runs. */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ATTACKS } from './evalkit/attacks.js';
import { corpusMarkdown, runCorpus } from './evalkit/corpus.js';
import { runAll } from './evalkit/golden.js';

const EVIDENCE = resolve(dirname(fileURLToPath(import.meta.url)), '../../evidence');
const stamp = (): string => new Date().toISOString().slice(0, 16).replace('T', ' ') + ' UTC';

async function main(): Promise<number> {
  mkdirSync(EVIDENCE, { recursive: true });
  const now = stamp();

  const results = await runAll();
  const corpus = await runCorpus();
  const n = results.length;
  const ok = results.filter((r) => r.passed).length;
  const rate = n ? ok / n : 0;
  const lines = [
    '# Setu agent — golden-task evaluation report',
    '',
    `*Generated by \`npm run evidence\` (TypeScript backend) on ${now}. Offline mode (ALLOW_OFFLINE=true, scripted LLM adapter), SAMPLE FX fixture (not live rates), all data SYNTHETIC. Numbers below come from an actual run.*`,
    '',
    `**Result: ${ok}/${n} tasks passed (${Math.round(rate * 100)}%)** — acceptance threshold 80%.`,
    '',
    '| ID | Task | Intent | Tier | Result | Checks |',
    '|---|---|---|---|---|---|',
    ...results.map(
      (r) =>
        `| ${r.id} | ${r.title} | ${r.intent} | ${r.tier} | ${r.passed ? 'PASS' : '**FAIL**'} | ${r.checks.filter((c) => c[1]).length}/${r.checks.length} |`
    ),
    '',
    '## Details',
    '',
  ];
  for (const r of results) {
    lines.push(
      `### ${r.id} — ${r.title} — ${r.passed ? 'PASS' : 'FAIL'}`,
      '',
      `Reply: > ${r.reply}`,
      ''
    );
    for (const [name, okc, detail] of r.checks)
      lines.push(`- ${okc ? '✔' : '✘'} ${name}${detail && !okc ? ': ' + detail : ''}`);
    lines.push('');
  }
  lines.push(
    ...corpusMarkdown(corpus),
    '## Method and limits',
    '',
    "- Each task runs in a fresh in-memory world (1 approver, 2 students, verified university payee, two obligations: CNY 1,350.00 due 2026-11-15 and CNY 18,500.00 due 2027-03-01; fixed 'today' 2026-10-17).",
    '- Expected numbers in eval/tasks.yaml were derived by hand from the fixture rate (CNY→BDT 17.2000, USD→CNY 7.1429) and the sandbox channel (USD 3.00 + 0.40%), not copied from program output.',
    '- Universal invariants checked on every task: no payment is executed by a chat turn; the trace has the 7 pipeline steps.',
    '- The scripted adapter is deterministic, so this measures the guardrails, tool wiring, policy tiers and reply validation — not open-ended LLM quality. Gemini/Groq adapters are not part of this evaluation.',
    ''
  );
  writeFileSync(resolve(EVIDENCE, 'eval_report.md'), lines.join('\n'));
  writeFileSync(
    resolve(EVIDENCE, 'eval_results.json'),
    JSON.stringify(
      {
        generated_at: now,
        total: n,
        passed: ok,
        pass_rate: Math.round(rate * 10000) / 10000,
        tasks: results.map((r) => ({
          id: r.id,
          title: r.title,
          passed: r.passed,
          intent: r.intent,
          tier: r.tier,
          checks: r.checks.map(([a, b, c]) => ({ name: a, ok: b, detail: c })),
        })),
      },
      null,
      2
    )
  );
  for (const r of results) console.log(`${r.passed ? 'PASS' : 'FAIL'} ${r.id} ${r.title}`);
  console.log(`golden pass rate ${Math.round(rate * 100)}% (${ok}/${n})`);

  const atk = [];
  for (const a of ATTACKS) atk.push(await a());
  const blocked = atk.filter((r) => r.blocked).length;
  const sec = [
    '# Setu — security test report (adversarial scenarios)',
    '',
    `*Generated by \`npm run evidence\` (TypeScript backend) on ${now}. Offline mode, in-memory SQLite, all data SYNTHETIC. Evidence lines are the actual observed responses of the running application code.*`,
    '',
    `**Result: ${blocked}/${atk.length} attacks blocked.**`,
    '',
    '| ID | Attack | Category | Blocked |',
    '|---|---|---|---|',
    ...atk.map(
      (r) =>
        `| ${r.id} | ${r.name} | ${r.category} | ${r.blocked ? '✔ blocked' : '**✘ NOT BLOCKED**'} |`
    ),
    '',
  ];
  for (const r of atk)
    sec.push(
      `## ${r.id} — ${r.name}`,
      '',
      `- **Attack:** ${r.attack}`,
      `- **Control:** ${r.control}`,
      `- **Outcome:** ${r.blocked ? 'BLOCKED' : 'NOT BLOCKED'}`,
      '- **Evidence:**',
      ...r.evidence.map((e) => `  - ${e}`),
      ''
    );
  sec.push(
    '## Scope and limits',
    '',
    '- These are targeted scenario tests of the implemented controls, not a penetration test or a formal audit.',
    '- Not covered: TLS/transport security, infrastructure hardening, dependency CVEs, side channels, real LLM providers (the default scripted adapter is deterministic), and attacks on the (simulated) bank. See `docs/SECURITY_SELF_ASSESSMENT.md` (KNOWN RISKS).',
    ''
  );
  writeFileSync(resolve(EVIDENCE, 'security_report.md'), sec.join('\n'));
  writeFileSync(
    resolve(EVIDENCE, 'security_results.json'),
    JSON.stringify(
      {
        generated_at: now,
        total: atk.length,
        blocked,
        attacks: atk.map((r) => ({
          id: r.id,
          name: r.name,
          category: r.category,
          blocked: r.blocked,
          evidence: r.evidence,
        })),
      },
      null,
      2
    )
  );
  for (const r of atk) console.log(`${r.blocked ? 'BLOCKED' : 'FAILED '} ${r.id} ${r.name}`);
  console.log(`${blocked}/${atk.length} attacks blocked`);
  return rate >= 0.8 && blocked === atk.length ? 0 : 1;
}

process.exit(await main());
