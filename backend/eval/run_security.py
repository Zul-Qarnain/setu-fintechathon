"""Runs every adversarial scenario and writes evidence/security_report.md (+ JSON). Real runs only."""

from __future__ import annotations

import json
import sys
from datetime import UTC, datetime
from pathlib import Path

from eval.attacks import ATTACKS, AttackResult

EVIDENCE = Path(__file__).resolve().parents[2] / "evidence"


def write_report(results: list[AttackResult], out_dir: Path = EVIDENCE) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    n, ok = len(results), sum(r.blocked for r in results)
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# Setu — security test report (adversarial scenarios)",
        "",
        f"*Generated by `make evidence` / `python -m eval.run_security` on {now}. Offline mode, in-memory SQLite, all data SYNTHETIC. "
        "Evidence lines are the actual observed responses of the running application code.*",
        "",
        f"**Result: {ok}/{n} attacks blocked.**",
        "",
        "| ID | Attack | Category | Blocked |",
        "|---|---|---|---|",
    ]
    for r in results:
        lines.append(f"| {r.id} | {r.name} | {r.category} | {'✔ blocked' if r.blocked else '**✘ NOT BLOCKED**'} |")
    lines.append("")
    for r in results:
        lines += [
            f"## {r.id} — {r.name}",
            "",
            f"- **Attack:** {r.attack}",
            f"- **Control:** {r.control}",
            f"- **Outcome:** {'BLOCKED' if r.blocked else 'NOT BLOCKED'}",
            "- **Evidence:**",
        ]
        lines += [f"  - {e}" for e in r.evidence]
        lines.append("")
    lines += [
        "## Scope and limits",
        "",
        "- These are targeted scenario tests of the implemented controls, not a penetration test or a formal audit.",
        "- Not covered: TLS/transport security, infrastructure hardening, dependency CVEs, side channels, real LLM providers (the default scripted adapter is deterministic), and attacks on the (simulated) bank. See `docs/SECURITY_SELF_ASSESSMENT.md` (KNOWN RISKS).",
        "",
    ]
    (out_dir / "security_report.md").write_text("\n".join(lines), encoding="utf-8")
    (out_dir / "security_results.json").write_text(
        json.dumps({"generated_at": now, "total": n, "blocked": ok,
                    "attacks": [{"id": r.id, "name": r.name, "category": r.category, "blocked": r.blocked, "evidence": r.evidence} for r in results]},
                   indent=2, ensure_ascii=False), encoding="utf-8")  # fmt: skip


def main() -> int:
    results = [a() for a in ATTACKS]
    write_report(results)
    for r in results:
        print(("BLOCKED " if r.blocked else "FAILED  ") + f"{r.id} {r.name}")
    print(f"{sum(r.blocked for r in results)}/{len(results)} attacks blocked")
    return 0 if all(r.blocked for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
